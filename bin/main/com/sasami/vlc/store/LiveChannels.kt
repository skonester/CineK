package com.sasami.vlc.store

import androidx.compose.runtime.*
import kotlinx.coroutines.*
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.io.File
import java.net.HttpURLConnection
import java.net.URI
import java.nio.file.Files
import java.nio.file.StandardCopyOption
import java.util.UUID

@Serializable
data class ChannelSource(val id: String, val name: String, val location: String)

@Serializable
data class LiveChannel(val sourceId: String, val name: String, val url: String,
    val group: String = "Uncategorized", val logo: String = "", val tvgId: String = "", val number: String = "") {
    fun playerItem() = PlayerItem(name, url, "stream", 0)
}

@Serializable
private data class ChannelData(val sources: List<ChannelSource> = emptyList(), val channels: List<LiveChannel> = emptyList())

/** The public FAST playlists are generated by BuddyChewChew/app-m3u-generator. */
data class FeaturedPlaylist(val name: String, val file: String) {
    val url get() = "https://raw.githubusercontent.com/BuddyChewChew/app-m3u-generator/main/playlists/$file"
}

object LiveChannels {
    val featured = listOf(
        Triple("Pluto TV", "plutotv", "us ca gb de fr es it br ar cl dk mx no se all"),
        Triple("Plex", "plex", "us ca gb au fr mx nz es all"),
        Triple("Samsung TV Plus", "samsungtvplus", "us ca gb de fr es it at ch in kr all")
    ).flatMap { (name, prefix, regions) ->
        regions.split(' ').map { region -> FeaturedPlaylist("$name · ${region.uppercase()}", "${prefix}_${region}.m3u") }
    } + FeaturedPlaylist("Roku Channel", "roku_all.m3u")
    var sources by mutableStateOf<List<ChannelSource>>(emptyList())
        private set
    var channels by mutableStateOf<List<LiveChannel>>(emptyList())
        private set
    var loading by mutableStateOf<String?>(null)
        private set
    var error by mutableStateOf<String?>(null)
        private set
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Main)
    private val json = Json { prettyPrint = true; ignoreUnknownKeys = true }
    private val file get() = File(AppPaths.configDir, "live-channels.json")

    fun load() {
        try {
            if (file.isFile) json.decodeFromString<ChannelData>(file.readText()).also {
                sources = it.sources; channels = it.channels
            }
        } catch (_: Exception) { error = "Could not read saved live channels." }
    }

    private fun save() {
        try {
            file.parentFile.mkdirs()
            val temporary = File(file.parentFile, "live-channels.json.tmp")
            temporary.writeText(json.encodeToString(ChannelData.serializer(), ChannelData(sources, channels)))
            Files.move(temporary.toPath(), file.toPath(), StandardCopyOption.REPLACE_EXISTING)
        } catch (_: Exception) { error = "Could not save live channels." }
    }

    fun add(name: String, location: String) {
        val value = location.trim()
        val uri = runCatching { URI(value) }.getOrNull()
        val remote = uri?.scheme?.lowercase() in setOf("http", "https") && !uri?.rawAuthority.isNullOrBlank()
        if (!remote && !File(value).isFile) { error = "Enter a playlist URL or choose an existing M3U file."; return }
        if (sources.any { it.location == value }) { error = "This playlist is already added."; return }
        val source = ChannelSource(UUID.randomUUID().toString(), name.trim().ifBlank { "Live playlist" }, value)
        sources = sources + source
        save()
        refresh(source)
    }

    fun remove(source: ChannelSource) {
        sources = sources - source
        channels = channels.filterNot { it.sourceId == source.id }
        save()
    }

    fun clearError() { error = null }

    fun refresh(source: ChannelSource) {
        if (loading != null) return
        error = null
        loading = source.id
        scope.launch {
            try {
                val loaded = withContext(Dispatchers.IO) { M3uChannels.parse(read(source.location), source.id, source.location) }
                if (loaded.isEmpty()) throw IllegalArgumentException("The playlist has no playable channels.")
                if (sources.any { it.id == source.id }) {
                    channels = channels.filterNot { it.sourceId == source.id } + loaded
                    save()
                }
            } catch (e: Exception) { error = "Could not load ${source.name}: ${e.message ?: "unknown error"}" }
            finally { loading = null }
        }
    }

    private fun read(location: String): String {
        val uri = runCatching { URI(location) }.getOrNull()
        val input = if (uri?.scheme?.lowercase() in setOf("http", "https")) {
            (uri!!.toURL().openConnection() as HttpURLConnection).apply {
                connectTimeout = 10000; readTimeout = 20000; instanceFollowRedirects = true
            }.inputStream
        } else File(location).inputStream()
        return input.use { stream ->
            val bytes = stream.readNBytes(32 * 1024 * 1024 + 1)
            if (bytes.size > 32 * 1024 * 1024) throw IllegalArgumentException("Playlist exceeds 32 MB")
            bytes.toString(Charsets.UTF_8)
        }
    }
}

object M3uChannels {
    private val attribute = Regex("([\\w-]+)\\s*=\\s*(?:\"([^\"]*)\"|'([^']*)'|([^\\s]+))")
    private val protocols = setOf("http", "https", "rtsp", "rtmp", "udp", "rtp")

    fun parse(text: String, sourceId: String, location: String): List<LiveChannel> {
        val lines = text.removePrefix("\uFEFF").lineSequence().map { it.trim() }.iterator()
        if (!lines.hasNext() || !lines.next().startsWith("#EXTM3U", true))
            throw IllegalArgumentException("This is not an M3U playlist.")
        if (text.contains("#EXT-X-TARGETDURATION", true) || text.contains("#EXT-X-STREAM-INF", true))
            throw IllegalArgumentException("This is an HLS stream URL, not a channel playlist. Open it as a stream.")
        val base = runCatching { URI(location) }.getOrNull()
        var metadata: Map<String, String> = emptyMap()
        var title = ""
        val found = LinkedHashMap<String, LiveChannel>()
        while (lines.hasNext()) {
            val line = lines.next()
            when {
                line.startsWith("#EXTINF:", true) -> {
                    val comma = metadataComma(line)
                    metadata = attribute.findAll(if (comma >= 0) line.substring(0, comma) else line)
                        .associate { it.groupValues[1].lowercase() to (it.groupValues[2].ifEmpty { it.groupValues[3].ifEmpty { it.groupValues[4] } }) }
                    title = if (comma >= 0) line.substring(comma + 1).trim() else ""
                }
                line.isBlank() || line.startsWith('#') -> Unit
                else -> {
                    val resolved = runCatching {
                        val uri = URI(line)
                        if (uri.isAbsolute) uri else base?.resolve(uri) ?: File(File(location).parentFile, line).toURI()
                    }.getOrNull()
                    if (resolved != null && resolved.scheme?.lowercase() in protocols) {
                        val url = resolved.toString()
                        found.putIfAbsent(url, LiveChannel(sourceId,
                            title.ifBlank { metadata["tvg-name"]?.takeIf { it.isNotBlank() } ?: "Channel ${found.size + 1}" }, url,
                            metadata["group-title"]?.takeIf { it.isNotBlank() } ?: "Uncategorized",
                            metadata["tvg-logo"].orEmpty(), metadata["tvg-id"].orEmpty(), metadata["tvg-chno"].orEmpty()))
                    }
                    metadata = emptyMap(); title = ""
                }
            }
        }
        return found.values.toList()
    }

    private fun metadataComma(line: String): Int {
        var quote: Char? = null
        line.forEachIndexed { index, char ->
            if (char == quote) quote = null
            else if (quote == null && (char == '\"' || char == '\'')) quote = char
            else if (quote == null && char == ',') return index
        }
        return -1
    }
}
