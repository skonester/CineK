@JsonClass(generateAdapter = true)
data class ChannelSource(val id: String, val name: String, val location: String)

@JsonClass(generateAdapter = true)
data class LiveChannel(
    val sourceId: String,
    val name: String,
    val url: String,
    val group: String = "Uncategorized",
    val logo: String = "",
    val tvgId: String = "",
    val number: String = "",
    /** Request headers the playlist asked for, such as User-Agent; sent only with this channel's stream. */
    val headers: Map<String, String> = emptyMap()
) {
    /**
     * Identifies the channel across playlist refreshes, for favorites and history.
     * Stream URLs can't do that because some services sign them per download, so this
     * prefers the guide id and falls back to the name. Channels sharing either within
     * one playlist share a key.
     */
    val key: String
        get() = "$sourceId|" + if (tvgId.isNotBlank()) "id:$tvgId" else "name:${name.trim().lowercase()}"
}

@JsonClass(generateAdapter = true)
data class WatchedChannel(val key: String, val watchedAt: Long)

@JsonClass(generateAdapter = true)
internal data class ChannelData(
    val sources: List<ChannelSource> = emptyList(),
    val channels: List<LiveChannel> = emptyList(),
    val favorites: List<String> = emptyList(),
    val history: List<WatchedChannel> = emptyList(),
    val favoriteCategories: List<String> = emptyList()
)

/** Identifies [group] within one playlist, for favorite categories. */
fun categoryKey(sourceId: String, group: String) = "$sourceId|$group"

/** The public FAST playlists are generated by BuddyChewChew/app-m3u-generator. */
data class FeaturedPlaylist(val name: String, val file: String) {
    val url get() = "https://raw.githubusercontent.com/BuddyChewChew/app-m3u-generator/main/playlists/$file"
}

data class LiveChannelState(
    val sources: List<ChannelSource> = emptyList(),
    val channels: List<LiveChannel> = emptyList(),
    /** [LiveChannel.key]s the viewer marked as favorites. */
    val favorites: Set<String> = emptySet(),
    /** Recently watched channels, newest first. */
    val history: List<WatchedChannel> = emptyList(),
    /** [categoryKey]s the viewer pinned to the front of the category list. */
    val favoriteCategories: Set<String> = emptySet(),
    /** The source currently downloading, if any. */
    val loadingSourceId: String? = null,
    val error: String? = null,
    /** False until the saved playlists have been read from disk. */
    val loaded: Boolean = false
)

/**
 * Live channel playlists, the Android counterpart of the desktop LiveChannels
 * store. Sources and their parsed channels are saved in the app's files so they
 * stay browsable offline between launches.
 */
@Singleton
class LiveChannelRepository @Inject constructor(
    @ApplicationContext private val context: Context,
    private val okHttpClient: OkHttpClient
) {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    private val adapter = Moshi.Builder().build().adapter(ChannelData::class.java)
    private val file get() = File(context.filesDir, "live-channels.json")
    private val saveLock = Mutex()
    private val _state = MutableStateFlow(LiveChannelState())
    val state: StateFlow<LiveChannelState> = _state.asStateFlow()
    private val _completedSaves = MutableStateFlow(0)
    /** Counts finished writes, so tests can wait for one without reading the file mid-write. */
    internal val completedSaves: StateFlow<Int> = _completedSaves.asStateFlow()

    init {
        // Holding the save lock means nothing can overwrite the file before it is read.
        scope.launch { saveLock.withLock { load() } }
    }

    private fun load() {
        val saved = runCatching { if (file.isFile) adapter.fromJson(file.readText()) else null }
        _state.update { current ->
            // Keep anything added while the file was being read.
            saved.getOrNull()?.let { data ->
                val savedIds = data.sources.mapTo(HashSet()) { it.id }
                current.copy(
                    sources = data.sources + current.sources.filterNot { it.id in savedIds },
                    channels = data.channels.filterNot { it.sourceId in current.sources.map(ChannelSource::id) } + current.channels,
                    favorites = data.favorites.toSet() + current.favorites,
                    history = (current.history + data.history).distinctBy { it.key }.take(MaxHistory),
                    favoriteCategories = data.favoriteCategories.toSet() + current.favoriteCategories,
                    loaded = true
                )
            } ?: current.copy(
                    loaded = true,
                    error = if (saved.isFailure) "Could not read saved live channels." else current.error
                )
        }
    }

    // Saves can overlap (an add and a finished download); write one at a time.
    private suspend fun save() = saveLock.withLock {
        val state = _state.value
        runCatching {
            val temporary = File(context.filesDir, "live-channels.json.tmp")
            temporary.writeText(adapter.toJson(ChannelData(
                state.sources, state.channels, state.favorites.toList(), state.history, state.favoriteCategories.toList()
            )))
            if (!temporary.renameTo(file)) {
                file.delete()
                check(temporary.renameTo(file))
            }
        }.onSuccess { _completedSaves.update { it + 1 } }
            .onFailure { _state.update { it.copy(error = "Could not save live channels.") } }
    }

    /** Adds a playlist and starts downloading it. Returns its id, or null with [LiveChannelState.error] set. */
    fun add(name: String, location: String): String? {
        val value = location.trim()
        val scheme = runCatching { Uri.parse(value).scheme?.lowercase() }.getOrNull()
        val valid = when (scheme) {
            "http", "https" -> !Uri.parse(value).host.isNullOrBlank()
            "content" -> true
            else -> false
        }
        if (!valid) {
            _state.update { it.copy(error = "Enter a playlist URL that starts with http:// or https://, or import an M3U file.") }
            return null
        }
        if (_state.value.sources.any { it.location == value }) {
            _state.update { it.copy(error = "This playlist is already added.") }
            return null
        }
        val source = ChannelSource(UUID.randomUUID().toString(), name.trim().ifBlank { "Live playlist" }, value)
        _state.update { it.copy(sources = it.sources + source, error = null) }
        scope.launch { save() }
        refresh(source)
        return source.id
    }

    fun remove(source: ChannelSource) {
        val prefix = "${source.id}|"
        _state.update { current ->
            current.copy(
                sources = current.sources - source,
                channels = current.channels.filterNot { it.sourceId == source.id },
                favorites = current.favorites.filterNotTo(HashSet()) { it.startsWith(prefix) },
                history = current.history.filterNot { it.key.startsWith(prefix) },
                favoriteCategories = current.favoriteCategories.filterNotTo(HashSet()) { it.startsWith(prefix) }
            )
        }
        scope.launch { save() }
    }

    fun toggleFavoriteCategory(sourceId: String, group: String) {
        val key = categoryKey(sourceId, group)
        _state.update {
            it.copy(favoriteCategories = if (key in it.favoriteCategories) it.favoriteCategories - key else it.favoriteCategories + key)
        }
        scope.launch { save() }
    }

    fun toggleFavorite(channel: LiveChannel) {
        val key = channel.key
        _state.update { it.copy(favorites = if (key in it.favorites) it.favorites - key else it.favorites + key) }
        scope.launch { save() }
    }

    /** Moves [channel] to the front of the recently watched list. */
    fun markWatched(channel: LiveChannel, now: Long = System.currentTimeMillis()) {
        val key = channel.key
        _state.update { current ->
            current.copy(history = (listOf(WatchedChannel(key, now)) + current.history.filterNot { it.key == key }).take(MaxHistory))
        }
        scope.launch { save() }
    }

    fun clearError() = _state.update { it.copy(error = null) }

    fun refresh(source: ChannelSource) {
        if (_state.value.loadingSourceId != null) return
        _state.update { it.copy(loadingSourceId = source.id, error = null) }
        scope.launch {
            try {
                val loaded = M3uChannels.parse(read(source.location), source.id, source.location)
                require(loaded.isNotEmpty()) { "The playlist has no playable channels." }
                _state.update { current ->
                    if (current.sources.none { it.id == source.id }) current
                    else current.copy(channels = current.channels.filterNot { it.sourceId == source.id } + loaded)
                }
                save()
            } catch (e: Exception) {
                _state.update { it.copy(error = "Could not load ${source.name}: ${e.message ?: "unknown error"}") }
            } finally {
                _state.update { it.copy(loadingSourceId = null) }
            }
        }
    }

    private fun read(location: String): String {
        val uri = Uri.parse(location)
        return when (uri.scheme?.lowercase()) {
            "http", "https" -> okHttpClient.newCall(Request.Builder().url(location).build()).execute().use { response ->
                check(response.isSuccessful) { "the server answered ${response.code}" }
                response.body?.byteStream()?.let(::readLimited) ?: error("the server sent no playlist")
            }
            "content" -> context.contentResolver.openInputStream(uri)?.use(::readLimited)
                ?: error("the file is no longer available")
            else -> error("unsupported playlist address")
        }
    }

    private fun readLimited(stream: InputStream): String {
        val bytes = stream.readNBytesCompat(MaxPlaylistBytes + 1)
        require(bytes.size <= MaxPlaylistBytes) { "Playlist exceeds 32 MB" }
        return bytes.toString(Charsets.UTF_8)
    }

    companion object {
        private const val MaxPlaylistBytes = 32 * 1024 * 1024
        private const val MaxHistory = 50

        val featured: List<FeaturedPlaylist> = listOf(
            Triple("Pluto TV", "plutotv", "us ca gb de fr es it br ar cl dk mx no se all"),
            Triple("Plex", "plex", "us ca gb au fr mx nz es all"),
            Triple("Samsung TV Plus", "samsungtvplus", "us ca gb de fr es it at ch in kr all")
        ).flatMap { (name, prefix, regions) ->
            regions.split(' ').map { region -> FeaturedPlaylist("$name · ${region.uppercase()}", "${prefix}_${region}.m3u") }
        } + FeaturedPlaylist("Roku Channel", "roku_all.m3u")
    }
}

// InputStream.readNBytes is API 33+; the app supports API 27.
private fun InputStream.readNBytesCompat(limit: Int): ByteArray {
    val output = java.io.ByteArrayOutputStream()
    val buffer = ByteArray(64 * 1024)
    while (output.size() < limit) {
        val read = read(buffer, 0, minOf(buffer.size, limit - output.size()))
        if (read < 0) break
        output.write(buffer, 0, read)
    }
    return output.toByteArray()
}

/**
 * The desktop M3U parser, plus the request headers that IPTV playlists attach to a
 * stream: Kodi-style `url|User-Agent=…&Referer=…` suffixes and VLC's
 * `#EXTVLCOPT:http-user-agent=` and `http-referrer=` lines.
 */
object M3uChannels {
    private val attribute = Regex("([\\w-]+)\\s*=\\s*(?:\"([^\"]*)\"|'([^']*)'|([^\\s]+))")
    private val protocols = setOf("http", "https", "rtsp", "rtmp", "udp", "rtp")

    /** The headers a playlist may set, by lowercase name. Anything else, cookies included, is dropped. */
    private val allowedHeaders = mapOf(
        "user-agent" to "User-Agent",
        "referer" to "Referer",
        "referrer" to "Referer",
        "origin" to "Origin"
    )
    private val vlcOptions = mapOf("http-user-agent" to "User-Agent", "http-referrer" to "Referer", "http-referer" to "Referer")
    private const val MaxHeaderLength = 1024

    /** [value] trimmed, or null when it is empty, too long, or could split the request with control characters. */
    private fun headerValue(value: String): String? =
        value.trim().takeIf { it.isNotEmpty() && it.length <= MaxHeaderLength && it.none { char -> char.isISOControl() } }

    /** The headers in a Kodi suffix, `User-Agent=Mozilla%2F5.0&Referer=…`, whose values are URL-encoded. */
    internal fun suffixHeaders(suffix: String): Map<String, String> = suffix.split('&').mapNotNull { pair ->
        val name = allowedHeaders[pair.substringBefore('=').trim().lowercase()] ?: return@mapNotNull null
        if ('=' !in pair) return@mapNotNull null
        // A stray % makes decoding fail; such a value is malformed, so the header is dropped.
        val decoded = runCatching { java.net.URLDecoder.decode(pair.substringAfter('='), "UTF-8") }.getOrNull()
        decoded?.let(::headerValue)?.let { name to it }
    }.toMap()

    private fun vlcHeader(line: String): Pair<String, String>? {
        val option = line.substringAfter(':')
        val name = vlcOptions[option.substringBefore('=').trim().lowercase()] ?: return null
        return headerValue(option.substringAfter('=', ""))?.let { name to it }
    }

    fun parse(text: String, sourceId: String, location: String): List<LiveChannel> {
        val lines = text.removePrefix("\uFEFF").lineSequence().map { it.trim() }.iterator()
        require(lines.hasNext() && lines.next().startsWith("#EXTM3U", true)) { "This is not an M3U playlist." }
        require(!text.contains("#EXT-X-TARGETDURATION", true) && !text.contains("#EXT-X-STREAM-INF", true)) {
            "This is an HLS stream address, not a channel playlist. Play it from Open › Play a stream."
        }
        // Relative entries only make sense next to a web playlist; a content:// file has no siblings.
        val base = runCatching { URI(location) }.getOrNull()?.takeIf { it.scheme?.lowercase() in setOf("http", "https") }
        var metadata: Map<String, String> = emptyMap()
        var title = ""
        var vlcHeaders: Map<String, String> = emptyMap()
        val found = LinkedHashMap<String, LiveChannel>()
        while (lines.hasNext()) {
            val line = lines.next()
            when {
                line.startsWith("#EXTINF:", true) -> {
                    val comma = metadataComma(line)
                    metadata = attribute.findAll(if (comma >= 0) line.substring(0, comma) else line)
                        .associate { it.groupValues[1].lowercase() to (it.groupValues[2].ifEmpty { it.groupValues[3].ifEmpty { it.groupValues[4] } }) }
                    title = if (comma >= 0) line.substring(comma + 1).trim() else ""
                }
                line.startsWith("#EXTVLCOPT:", true) -> vlcHeader(line)?.let { vlcHeaders = vlcHeaders + it }
                line.isBlank() || line.startsWith('#') -> Unit
                else -> {
                    val resolved = runCatching {
                        val uri = URI(line.substringBefore('|').trim())
                        if (uri.isAbsolute) uri else base?.resolve(uri)
                    }.getOrNull()
                    if (resolved != null && resolved.scheme?.lowercase() in protocols) {
                        val url = resolved.toString()
                        // Only HTTP requests carry headers. The suffix wins over a VLC option for the same header.
                        val headers = if (resolved.scheme.lowercase() in setOf("http", "https")) {
                            vlcHeaders + suffixHeaders(line.substringAfter('|', ""))
                        } else emptyMap()
                        found.putIfAbsent(url, LiveChannel(sourceId,
                            title.ifBlank { metadata["tvg-name"]?.takeIf { it.isNotBlank() } ?: "Channel ${found.size + 1}" }, url,
                            metadata["group-title"]?.takeIf { it.isNotBlank() } ?: "Uncategorized",
                            metadata["tvg-logo"].orEmpty(), metadata["tvg-id"].orEmpty(), metadata["tvg-chno"].orEmpty(),
                            headers))
                    }
                    metadata = emptyMap(); title = ""; vlcHeaders = emptyMap()
                }
            }
        }
        return found.values.toList()
    }

    private fun metadataComma(line: String): Int {
        var quote: Char? = null
        line.forEachIndexed { index, char ->
            if (char == quote) quote = null
            else if (quote == null && (char == '"' || char == '\'')) quote = char
            else if (quote == null && char == ',') return index
        }
        return -1
    }
}
